// 在庫一覧が、コード順の先頭の制限に関係なく、必ず一覧に出す薬品の条件。
//
// 在庫の数がある薬品(正)に加えて、マイナス在庫の薬品も含める。マイナス在庫は薬歴完了で許される状態で、
// 「マイナス在庫が N 件あります」の件数と「0へ補正」の操作は一覧の薬品から作られる。
// 在庫が正の薬品だけを足していたため、コード順の後ろにあるマイナス在庫の薬品は一覧にも件数にも出ず、補正できなかった。
// 在庫数が未設定(null / 無し)や 0 の薬品は含めない(全薬品を読み込んでしまう)。
export const DRUGS_WITH_RECORDED_STOCK_SELECTOR = {
  isAbolished: { $ne: true },
  $or: [{ stockQuantity: { $gt: 0 } }, { stockQuantity: { $lt: 0 } }]
};
